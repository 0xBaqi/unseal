/**
 * verifier.unit.test.js — Unit tests for the NEP-413 authentication proof.
 *
 * Label: [SIMULATED] — All tests use a mock RPC provider and a known test
 * key pair generated from a fixed seed. No real wallet or testnet RPC is
 * involved. Tests are fully deterministic and reproducible.
 *
 * Test vector provenance:
 *   - Private key: 32 bytes of 0x01 (test-only seed, never used on any network)
 *   - Public key derived via @noble/curves/ed25519 (same library as near-api-js)
 *   - Signature computed by signing the exact Borsh+SHA-256 payload that
 *     near-api-js verifyMessage constructs, ensuring the vector is consistent
 *     with the library's own serialization.
 *   - Vector was generated by /test/gen_vector.js and recorded here verbatim.
 *
 * To regenerate vectors: node --input-type=module test/gen_vector.js
 */

import { describe, it, before, beforeEach, afterEach } from 'node:test';
import assert from 'node:assert/strict';

import { issueChallenge, consumeChallenge, _clearStore, _peekChallenge, _storeSize, DEFAULT_TTL_MS, NONCE_BYTES } from '../src/challenge.js';
import { verifyAuth, UNSEAL_RECIPIENT } from '../src/verifier.js';

// ── Known test vectors ──────────────────────────────────────────────────────
// Generated from: private key = 0x01 * 32, nonce = 0xAB * 32
// See generation script comments above.

const TV = {
  ACCOUNT_ID: 'test.testnet',
  PUBLIC_KEY: 'ed25519:AKnL4NNf3DGWZJS6cPknBuEGnVsV4A4m5tgebLHaRSZ9',
  NONCE_B64: 'q6urq6urq6urq6urq6urq6urq6urq6urq6urq6urq6s=',
  SIG_B64: 'JayYJoskxyEVkqw3cEUgT9RG3si8lqdiCAMrfKly52pUKzX5Gp6SLL3txSS3aH86Qx1DpV0bKBvXAZ7z8eiHAQ==',
  MESSAGE: 'Sign in to Unseal Gate A.2 proof',
  RECIPIENT: UNSEAL_RECIPIENT,
};

// ── Mock provider ───────────────────────────────────────────────────────────

/**
 * Build a mock JsonRpcProvider that returns the given access key permission
 * for view_access_key calls, without hitting the network.
 *
 * @param {object} opts
 * @param {'FullAccess'|string} [opts.permission='FullAccess']
 * @param {boolean} [opts.shouldThrow=false] - Simulate RPC failure
 * @param {string} [opts.errorMsg]
 */
function makeMockProvider({ permission = 'FullAccess', shouldThrow = false, errorMsg = 'RPC failure' } = {}) {
  return {
    async viewAccessKey({ accountId, publicKey }) {
      if (shouldThrow) throw new Error(errorMsg);
      return { permission, nonce: 1 };
    },
  };
}

// ── Helpers ─────────────────────────────────────────────────────────────────

function decodeNonce(nonceB64) {
  return new Uint8Array(Buffer.from(nonceB64, 'base64'));
}

function decodeSignature(sigB64) {
  return new Uint8Array(Buffer.from(sigB64, 'base64'));
}

/** Build a valid verifyAuth call with the known test vector. */
function validAuthArgs(overrides = {}) {
  return {
    accountId: TV.ACCOUNT_ID,
    publicKey: TV.PUBLIC_KEY,
    signature: decodeSignature(TV.SIG_B64),
    message: TV.MESSAGE,
    recipient: TV.RECIPIENT,
    nonce: decodeNonce(TV.NONCE_B64),
    provider: makeMockProvider({ permission: 'FullAccess' }),
    ...overrides,
  };
}

// ── Test suites ──────────────────────────────────────────────────────────────

// ════════════════════════════════════════════════════════════
// SUITE 1: challenge.js — nonce lifecycle
// ════════════════════════════════════════════════════════════
describe('[SIMULATED] challenge — nonce lifecycle', () => {
  beforeEach(() => _clearStore());

  it('issues a challenge and returns required fields', () => {
    const result = issueChallenge({
      accountId: 'alice.testnet',
      recipient: UNSEAL_RECIPIENT,
      message: 'Test',
    });
    assert.ok(result.nonceB64, 'nonceB64 must be present');
    assert.equal(result.accountId, 'alice.testnet');
    assert.equal(result.recipient, UNSEAL_RECIPIENT);
    assert.equal(result.message, 'Test');
    assert.ok(result.expiresAt > Date.now(), 'expiresAt must be in the future');
  });

  it('nonce is exactly 32 bytes', () => {
    const { nonceB64 } = issueChallenge({ accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT, message: 'x' });
    const bytes = Buffer.from(nonceB64, 'base64');
    assert.equal(bytes.length, NONCE_BYTES, `Nonce must be ${NONCE_BYTES} bytes`);
  });

  it('two issued challenges produce different nonces', () => {
    const a = issueChallenge({ accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT, message: 'x' });
    const b = issueChallenge({ accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT, message: 'x' });
    assert.notEqual(a.nonceB64, b.nonceB64, 'Nonces must be unique');
  });

  it('consumes a valid challenge successfully', () => {
    const { nonceB64 } = issueChallenge({ accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT, message: 'hello' });
    const { nonce, message } = consumeChallenge({ nonceB64, accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT });
    assert.ok(nonce instanceof Uint8Array, 'nonce must be Uint8Array');
    assert.equal(nonce.length, 32);
    assert.equal(message, 'hello');
  });

  it('[NEGATIVE] replay: consuming the same nonce twice throws', () => {
    const { nonceB64 } = issueChallenge({ accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT, message: 'x' });
    consumeChallenge({ nonceB64, accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT });
    assert.throws(
      () => consumeChallenge({ nonceB64, accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT }),
      (err) => {
        assert.ok(err.message.includes('CHALLENGE_NOT_FOUND') || err.message.includes('CHALLENGE_REPLAY'), err.message);
        return true;
      }
    );
  });

  it('[NEGATIVE] unknown nonce throws CHALLENGE_NOT_FOUND', () => {
    assert.throws(
      () => consumeChallenge({ nonceB64: 'aaaa', accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT }),
      (err) => { assert.ok(err.message.includes('CHALLENGE_NOT_FOUND'), err.message); return true; }
    );
  });

  it('[NEGATIVE] expired challenge throws CHALLENGE_EXPIRED', () => {
    const { nonceB64 } = issueChallenge({ accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT, message: 'x', ttlMs: 1 });
    // Wait 2ms for it to expire
    const start = Date.now();
    while (Date.now() - start < 5) {} // busy-wait (small test, no async needed)
    assert.throws(
      () => consumeChallenge({ nonceB64, accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT }),
      (err) => { assert.ok(err.message.includes('CHALLENGE_EXPIRED'), err.message); return true; }
    );
  });

  it('[NEGATIVE] wrong account ID throws CHALLENGE_ACCOUNT_MISMATCH', () => {
    const { nonceB64 } = issueChallenge({ accountId: 'alice.testnet', recipient: UNSEAL_RECIPIENT, message: 'x' });
    assert.throws(
      () => consumeChallenge({ nonceB64, accountId: 'eve.testnet', recipient: UNSEAL_RECIPIENT }),
      (err) => { assert.ok(err.message.includes('CHALLENGE_ACCOUNT_MISMATCH'), err.message); return true; }
    );
  });

  it('[NEGATIVE] wrong recipient throws CHALLENGE_RECIPIENT_MISMATCH', () => {
    const { nonceB64 } = issueChallenge({ accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT, message: 'x' });
    assert.throws(
      () => consumeChallenge({ nonceB64, accountId: 'a.testnet', recipient: 'evil-app.com' }),
      (err) => { assert.ok(err.message.includes('CHALLENGE_RECIPIENT_MISMATCH'), err.message); return true; }
    );
  });

  it('store is empty after consuming a challenge', () => {
    const { nonceB64 } = issueChallenge({ accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT, message: 'x' });
    assert.equal(_storeSize(), 1);
    consumeChallenge({ nonceB64, accountId: 'a.testnet', recipient: UNSEAL_RECIPIENT });
    assert.equal(_storeSize(), 0, 'Store must be empty after consumption');
  });
});

// ════════════════════════════════════════════════════════════
// SUITE 2: verifier.js — cryptographic verification
// ════════════════════════════════════════════════════════════
describe('[SIMULATED] verifier — cryptographic verification with known test vector', () => {

  it('[POSITIVE] verifyAuth succeeds with valid signature, key, nonce, recipient', async () => {
    const result = await verifyAuth(validAuthArgs());
    assert.equal(result.ok, true);
    assert.equal(result.accountId, TV.ACCOUNT_ID);
    assert.equal(result.publicKey, TV.PUBLIC_KEY);
  });

  it('[NEGATIVE] tampered message: flip one char in message → signature invalid', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ message: TV.MESSAGE + 'X' })),
      (err) => { assert.ok(err.code === 'BAD_SIGNATURE' || err.code === 'VERIFICATION_FAILED', `code=${err.code}: ${err.message}`); return true; }
    );
  });

  it('[NEGATIVE] tampered nonce: one byte changed → signature invalid', async () => {
    const badNonce = decodeNonce(TV.NONCE_B64);
    badNonce[0] ^= 0xFF; // flip first byte
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ nonce: badNonce })),
      (err) => { assert.ok(err.code === 'BAD_SIGNATURE' || err.code === 'VERIFICATION_FAILED', `code=${err.code}: ${err.message}`); return true; }
    );
  });

  it('[NEGATIVE] wrong recipient → RECIPIENT_MISMATCH before crypto', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ recipient: 'attacker-app.com' })),
      (err) => { assert.equal(err.code, 'RECIPIENT_MISMATCH', err.message); return true; }
    );
  });

  it('[NEGATIVE] all-zeros signature (malformed) → signature invalid', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ signature: new Uint8Array(64) })),
      (err) => { assert.ok(err.code === 'BAD_SIGNATURE' || err.code === 'VERIFICATION_FAILED', `code=${err.code}: ${err.message}`); return true; }
    );
  });

  it('[NEGATIVE] signature wrong length (63 bytes) → INVALID_INPUT', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ signature: new Uint8Array(63) })),
      (err) => { assert.equal(err.code, 'INVALID_INPUT', err.message); return true; }
    );
  });

  it('[NEGATIVE] nonce wrong length (31 bytes) → INVALID_INPUT', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ nonce: new Uint8Array(31) })),
      (err) => { assert.equal(err.code, 'INVALID_INPUT', err.message); return true; }
    );
  });

  it('[NEGATIVE] RPC failure → fails closed (VERIFICATION_FAILED or RPC_FAILURE, never ok)', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ provider: makeMockProvider({ shouldThrow: true }) })),
      (err) => {
        assert.ok(err.code === 'RPC_FAILURE' || err.code === 'VERIFICATION_FAILED', `code=${err.code}: ${err.message}`);
        return true;
      }
    );
  });

  it('[NEGATIVE] key exists but is FunctionCall (not FullAccess) → NOT_FULL_ACCESS_KEY', async () => {
    // near-api-js verifyMessage explicitly checks for FullAccess and throws if not
    await assert.rejects(
      () => verifyAuth(validAuthArgs({
        provider: makeMockProvider({ permission: { FunctionCall: { allowance: null, receiver_id: 'x.near', method_names: [] } } })
      })),
      (err) => {
        assert.ok(
          err.code === 'NOT_FULL_ACCESS_KEY' || err.code === 'VERIFICATION_FAILED',
          `code=${err.code}: ${err.message}`
        );
        return true;
      }
    );
  });

  it('[NEGATIVE] key not found on chain → KEY_NOT_ON_CHAIN or VERIFICATION_FAILED', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({
        provider: makeMockProvider({ shouldThrow: true, errorMsg: 'key not found on account' })
      })),
      (err) => {
        assert.ok(
          err.code === 'KEY_NOT_ON_CHAIN' || err.code === 'VERIFICATION_FAILED' || err.code === 'RPC_FAILURE',
          `code=${err.code}: ${err.message}`
        );
        return true;
      }
    );
  });

  it('[NEGATIVE] wrong account ID in payload: mock RPC returns key-not-found', async () => {
    // The public key belongs to test.testnet, not to impersonated.testnet
    await assert.rejects(
      () => verifyAuth(validAuthArgs({
        accountId: 'impersonated.testnet',
        provider: makeMockProvider({ shouldThrow: true, errorMsg: 'does not exist' })
      })),
      (err) => {
        assert.ok(err.code !== undefined, `Error must have a code: ${err.message}`);
        return true;
      }
    );
  });

  it('[NEGATIVE] missing accountId → INVALID_INPUT', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ accountId: '' })),
      (err) => { assert.equal(err.code, 'INVALID_INPUT', err.message); return true; }
    );
  });

  it('[NEGATIVE] missing publicKey → INVALID_INPUT', async () => {
    await assert.rejects(
      () => verifyAuth(validAuthArgs({ publicKey: '' })),
      (err) => { assert.equal(err.code, 'INVALID_INPUT', err.message); return true; }
    );
  });
});

// ════════════════════════════════════════════════════════════
// SUITE 3: Integration — challenge + verify pipeline
// ════════════════════════════════════════════════════════════
describe('[SIMULATED] full pipeline — challenge issue → consume → verify', () => {
  beforeEach(() => _clearStore());

  it('[POSITIVE] full happy path: issue, consume, verify succeeds', async () => {
    // Issue a challenge with the known message
    const challenge = issueChallenge({
      accountId: TV.ACCOUNT_ID,
      recipient: TV.RECIPIENT,
      message: TV.MESSAGE,
    });

    // Consume the challenge (simulates server receiving the signed response)
    const { nonce, message } = consumeChallenge({
      nonceB64: challenge.nonceB64,
      accountId: TV.ACCOUNT_ID,
      recipient: TV.RECIPIENT,
    });

    // The nonce from consumeChallenge must equal the nonce that was signed in our test vector
    // For the full pipeline test, we override with the known test vector nonce and sig
    // because our challenge nonce is random (not the fixed test vector nonce).
    // This validates the pipeline contract, not the specific nonce bytes.
    const result = await verifyAuth({
      accountId: TV.ACCOUNT_ID,
      publicKey: TV.PUBLIC_KEY,
      signature: decodeSignature(TV.SIG_B64),
      message: TV.MESSAGE,
      recipient: TV.RECIPIENT,
      nonce: decodeNonce(TV.NONCE_B64), // known test vector nonce
      provider: makeMockProvider({ permission: 'FullAccess' }),
    });

    assert.equal(result.ok, true);
    assert.equal(_storeSize(), 0, 'Nonce must be consumed from store');
  });

  it('[NEGATIVE] nonce consumed on first verify: second verify attempt fails', async () => {
    const challenge = issueChallenge({
      accountId: TV.ACCOUNT_ID,
      recipient: TV.RECIPIENT,
      message: TV.MESSAGE,
    });

    // First consume — succeeds
    consumeChallenge({ nonceB64: challenge.nonceB64, accountId: TV.ACCOUNT_ID, recipient: TV.RECIPIENT });

    // Second consume with same nonce — must fail
    assert.throws(
      () => consumeChallenge({ nonceB64: challenge.nonceB64, accountId: TV.ACCOUNT_ID, recipient: TV.RECIPIENT }),
      (err) => { assert.ok(err.message.includes('CHALLENGE_NOT_FOUND'), err.message); return true; }
    );
  });
});
